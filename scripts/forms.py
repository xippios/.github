#!/usr/bin/env python3
"""The issue forms and the PR template of this repository, generated from the style of the record.

``docs/style/issues.md`` and ``pulls.md`` of a coordinate root name the sections of every template
(C73). A form has one field per section, in the same order and with the same names; it carries
its issue type (C74) and no title prefix, and no "Requested by" field, since the account and the
label say who filed (C62). The style lives in the private roots, so the coordinator runs this
script on a root's ``docs/style/`` and the PR carries the output (.github#19)::

    python3 scripts/forms.py --style ~/github/coordinate/docs/style --out .
    python3 scripts/forms.py --style ~/github/coordinate/docs/style --out . --check

``--check`` writes nothing and exits 1 when a file differs from what the style gives.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

FENCE = re.compile(r"^```")
SECTION = re.compile(r"^- `## (?P<name>[^`]+)`(?P<required> \(never left out\))?: (?P<text>.*)$")
CLOSES = re.compile(r"^- `Closes <URL>`: (?P<text>.*)$")
ROW = re.compile(r"^\| (?P<key>[^|]+?) \| (?P<value>.*) \|$")
FORMS = Path(".github") / "ISSUE_TEMPLATE"
PR_TEMPLATE = Path(".github") / "pull_request_template.md"
HEADER = (
    "# Generated by scripts/forms.py from docs/style/issues.md of a coordinate root (C73, C74).\n"
    "# Edit the style and generate again; never this file.\n"
)


@dataclass(frozen=True)
class Section:
    """One section of a template: its heading, whether it is never left out, what it holds."""

    name: str
    required: bool
    text: str


@dataclass(frozen=True)
class Template:
    """A template of the style: its table (Marker, Written by, Title) and its sections."""

    table: dict[str, str]
    sections: tuple[Section, ...]
    closes: str | None


@dataclass(frozen=True)
class Kind:
    """An issue type and the template of the style its form follows (None: no template)."""

    type: str
    name: str
    about: str
    block: str | None
    labels: tuple[str, ...] = ()


KINDS = (
    # A row is proposed until accepted, as `coordinate issue new` labels it.
    Kind(
        "change",
        "Change",
        "A change requested of this repository.",
        "Row: change or gap",
        ("proposed",),
    ),
    Kind(
        "gap", "Gap", "A gap: what was seen, where, and how.", "Row: change or gap", ("proposed",)
    ),
    Kind("package", "Package", "A package with its plan and milestone.", "Package", ("proposed",)),
    Kind(
        "question",
        "Question",
        "A question for the human, recommendation first; the answer is the decision (G5).",
        "Question",
        ("gate:G5",),
    ),
    Kind("gate", "Gate", "A human action, assigned to the human.", "Gate"),
    Kind("note", "Note", "Intake from outside, triaged with `coordinate inbox file`.", None),
)


def blocks(text: str) -> dict[str, list[str]]:
    """The level-2 blocks of a style file by heading; a fenced example stays in its block."""
    out: dict[str, list[str]] = {}
    current: list[str] | None = None
    fenced = False
    for line in text.splitlines():
        if FENCE.match(line):
            fenced = not fenced
        elif not fenced and line.startswith("## "):
            current = out.setdefault(line[3:].strip(), [])
            continue
        if current is not None:
            current.append(line)
    return out


def bullets(lines: list[str]) -> list[str]:
    """The top-level bullets of a block outside its fences, continuation lines joined."""
    items: list[str] = []
    fenced = open_item = False
    for line in lines:
        if FENCE.match(line):
            fenced, open_item = not fenced, False
        elif fenced:
            continue
        elif line.startswith("- "):
            items.append(line)
            open_item = True
        elif open_item and line.startswith("  ") and line.strip():
            items[-1] += " " + line.strip()
        else:
            open_item = False
    return items


def example_headings(lines: list[str]) -> list[str]:
    """The ``##`` headings inside a block's fenced example."""
    fenced = False
    out: list[str] = []
    for line in lines:
        if FENCE.match(line):
            fenced = not fenced
        elif fenced and line.startswith("## "):
            out.append(line[3:].strip())
    return out


def template(lines: list[str]) -> Template:
    """A block read as a template: the section bullets, else the headings of its example."""
    table = {}
    for line in lines:
        m = ROW.match(line)
        if m and m["key"].strip() != "---":
            table[m["key"].strip()] = m["value"].strip()
    sections: list[Section] = []
    closes = None
    for item in bullets(lines):
        if m := SECTION.match(item):
            sections.append(Section(m["name"], bool(m["required"]), m["text"]))
        elif m := CLOSES.match(item):
            closes = m["text"]
    if not sections:
        sections = [Section(name, True, "") for name in example_headings(lines)]
    return Template(table, tuple(sections), closes)


def read(path: Path, heading: str) -> Template:
    """The template under ``## <heading>`` of a style file; a missing one stops the run."""
    found = blocks(path.read_text()).get(heading)
    if found is None:
        raise SystemExit(f"forms: {path.name} has no `## {heading}`")
    t = template(found)
    if not t.sections:
        raise SystemExit(f"forms: `## {heading}` of {path.name} names no section")
    return t


def slug(name: str) -> str:
    """A field id from a section's name: ``Other options`` gives ``other-options``."""
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def quoted(text: str) -> str:
    """A YAML double-quoted scalar (JSON's string syntax is YAML's)."""
    return json.dumps(text, ensure_ascii=False)


def title(kind: Kind, t: Template) -> str:
    """The title rule of a kind: its part of the template's Title row when the row names kinds."""
    row = t.table.get("Title", "")
    parts = [p.strip() for p in row.split("; ")]
    return next((p for p in parts if re.search(rf"\b{kind.type}\b", p)), row)


def form(kind: Kind, t: Template | None) -> str:
    """The issue form of a kind."""
    sections = t.sections if t else (Section("Note", True, ""),)
    about = kind.about + (f" Title: {title(kind, t)}." if t and t.table.get("Title") else "")
    lines = [HEADER + f"name: {kind.name}", f"description: {quoted(about)}", f"type: {kind.type}"]
    if kind.labels:
        lines.append(f"labels: {json.dumps(list(kind.labels))}")
    lines.append("body:")
    for s in sections:
        lines += ["  - type: textarea", f"    id: {slug(s.name)}", "    attributes:"]
        lines.append(f"      label: {quoted(s.name)}")
        if s.text:
            lines.append(f"      description: {quoted(s.text)}")
        if s.required:
            lines += ["    validations:", "      required: true"]
    return "\n".join(lines) + "\n"


def for_people(text: str) -> str:
    """A section's text for a person filling the template: the CLI's own sentences left out."""
    sentences = re.split(r"(?<=\.) ", text)
    kept = " ".join(s for s in sentences if not s.startswith("The CLI"))
    if "--" in kept:
        raise SystemExit(f"forms: `{kept}` cannot stand inside an HTML comment")
    return kept


def pr_template(t: Template) -> str:
    """The PR template: every section with its rule as a hidden comment, then the Closes line."""
    out: list[str] = []
    for s in t.sections:
        out += [f"## {s.name}", "", f"<!-- {for_people(s.text)} -->", ""]
        if s.name == "Decisions taken":
            out += ["None.", ""]
    if t.closes:
        out += [f"<!-- {for_people(t.closes)} -->", "Closes <URL>"]
    return "\n".join(out).rstrip() + "\n"


def generate(style: Path) -> dict[Path, str]:
    """Every generated file by its path in the repository."""
    issues, pulls = style / "issues.md", style / "pulls.md"
    files = {
        FORMS / f"{k.type}.yml": form(k, read(issues, k.block) if k.block else None) for k in KINDS
    }
    files[PR_TEMPLATE] = pr_template(read(pulls, "PR"))
    return files


def main(argv: list[str] | None = None) -> int:
    """Write the forms and the PR template, or with ``--check`` name the ones that differ."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--style", type=Path, required=True, help="a root's docs/style/")
    parser.add_argument("--out", type=Path, default=Path(), help="this repository's checkout")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 on drift")
    args = parser.parse_args(argv)
    files = generate(args.style)
    if args.check:
        stale = [
            rel
            for rel, text in files.items()
            if not (args.out / rel).is_file() or (args.out / rel).read_text() != text
        ]
        for rel in stale:
            print(f"forms: {rel} differs from docs/style")
        return 1 if stale else 0
    for rel, text in files.items():
        (args.out / rel).parent.mkdir(parents=True, exist_ok=True)
        (args.out / rel).write_text(text)
        print(f"forms: wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
